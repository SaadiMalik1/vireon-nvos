import os
from typing import Dict, Any

class BenchmarkReporter:
    """
    Generates a formal Markdown report from the benchmark JSON results.
    """
    def __init__(self, report_data: Dict[str, Any], output_dir: str):
        self.report_data = report_data
        self.output_dir = output_dir

    def generate_markdown(self) -> str:
        summary = self.report_data["summary"]
        categories = self.report_data["categories"]
        results = self.report_data["results"]
        
        md = []
        md.append("# VIREON Benchmark Suite Report\n")
        
        md.append("## Executive Summary\n")
        md.append(f"- **Total Scenarios Run:** {summary['total_run']}")
        md.append(f"- **Total Passed:** {summary['passed']}")
        md.append(f"- **Total Failed:** {summary['failed']}")
        md.append(f"- **Global Seed:** `{summary['seed']}`")
        
        overall_score = summary['score']
        md.append(f"- **VIREON Validation Score:** **{overall_score:.1f}%**\n")
        
        if overall_score == 100.0:
            md.append("> [!TIP]")
            md.append("> All benchmarks passed successfully.\n")
        elif overall_score >= 80.0:
            md.append("> [!NOTE]")
            md.append("> Most benchmarks passed, but some vulnerabilities remain.\n")
        else:
            md.append("> [!WARNING]")
            md.append("> Significant failures detected. Security posture is inadequate.\n")

        md.append("## Categorical Breakdown\n")
        md.append("| Category | Total | Passed | Failed | Score |")
        md.append("|---|---|---|---|---|")
        for cat, stats in sorted(categories.items()):
            md.append(f"| {cat.capitalize()} | {stats['total']} | {stats['passed']} | {stats['failed']} | {stats['score']:.1f}% |")
        md.append("\n")
        
        md.append("## Scenario Results\n")
        md.append("| Status | Scenario ID | Category | Execution Hash | Details |")
        md.append("|:---:|---|---|---|---|")
        for r in results:
            status_emoji = "✅" if r["passed"] else "❌"
            # Extract just the bundle folder name for a shorter link
            bundle_name = os.path.basename(r["bundle_path"])
            # The link points to the local directory where the report is generated
            details_link = f"[{bundle_name}](./{bundle_name}/manifest.json)"
            md.append(f"| {status_emoji} | `{r['experiment_id']}` | {r['category']} | `{r['execution_hash']}` | {details_link} |")
        
        md.append("\n---\n*Report generated by VIREON Benchmark Suite*")
        
        content = "\n".join(md)
        report_path = os.path.join(self.output_dir, "benchmark_report.md")
        with open(report_path, "w") as f:
            f.write(content)
            
        return report_path
